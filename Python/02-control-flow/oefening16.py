# Oppervlaktecalculator 📏

import math

basis = 20
hoogte = 30
oppervlakte = basis * hoogte / 2

print("The oppervlakte van de driehoek is", oppervlakte)

lengte = 2
breedte = 12
oppervlakte = lengte * breedte

print("De oppervlakte van de rechthoek is", oppervlakte)
    
radius = 36
oppervlakte = math.pi * radius * radius
    
print("De oppervlakte van de cirkel is", oppervlakte)