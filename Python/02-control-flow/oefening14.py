# Gelukskoekje Program 🥠

import random

fortune = random.randint(0, 4)

if fortune == 0:
  print("Moge je ooit CO2-belastend zijn")
elif fortune == 1:  
  print("Je hebt rijst tussen je tanden")
elif fortune == 2:
  print("Geen enkele sneeuwvlok voelt zich verantwoordelijk voor een lawine")
elif fortune == 3:
  print("Je kunt alleen de punten verbinden als je achteruit kijkt")
elif fortune == 4:
  print("Het geluk dat je zoekt zit in een andere koekje")